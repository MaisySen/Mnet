package main

import (
	"fmt"
	"os"
)

func isServiceSession() bool       { return false }
func runAsService(o options) error { return fmt.Errorf("use the generated systemd unit on Linux") }

// print-unit only writes text to stdout. It never installs/enables/starts a
// service, changes host files or initializes/replaces the device identity.
func runServiceAction(o options) error {
	if o.serviceAction != "print-unit" {
		return fmt.Errorf("Linux supports -service print-unit only; installation is separate")
	}
	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate executable: %w", err)
	}
	unit, err := linuxServiceUnit(exe, o)
	if err != nil {
		return err
	}
	_, err = fmt.Fprint(os.Stdout, unit)
	return err
}

func linuxServiceUnit(exe string, o options) (string, error) {
	if err := validateSavedService(exe, o); err != nil {
		return "", err
	}
	return fmt.Sprintf(`# Generated by mnetd -service print-unit. Review before installing.
# Enroll first with this same private state directory. Contains no auth key.
# Service running is not VPN readiness; use authenticated mnet wait/status.
[Unit]
Description=Mnet node daemon
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
UMask=0077
ExecStart=%s -state %s -ifname %s -up
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
`, exe, o.stateDir, o.ifname), nil
}
