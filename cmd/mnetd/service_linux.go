//go:build linux

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func isServiceSession() bool       { return false }
func runAsService(o options) error { return fmt.Errorf("use the generated systemd unit on Linux") }

// print-unit only writes text to stdout. It never installs/enables/starts a
// service, changes host files or initializes/replaces the device identity.
func runServiceAction(o options) error {
	if o.serviceAction != "print-unit" {
		return fmt.Errorf("Linux supports -service print-unit only; installation is separate")
	}
	exe, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate executable: %w", err)
	}
	unit, err := linuxServiceUnit(exe, o)
	if err != nil {
		return err
	}
	_, err = fmt.Fprint(os.Stdout, unit)
	return err
}

func linuxServiceUnit(exe string, o options) (string, error) {
	// Conservative literal tokens prevent systemd specifier/environment/quoting
	// expansion. Unsupported paths fail rather than generating a different argv.
	safe := func(value string) bool {
		if value == "" {
			return false
		}
		for _, c := range value {
			if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || strings.ContainsRune("/._-", c)) {
				return false
			}
		}
		return true
	}
	if !filepath.IsAbs(exe) || !filepath.IsAbs(o.stateDir) || !safe(exe) || !safe(o.stateDir) || filepath.Clean(o.stateDir) == "/" || filepath.Clean(o.stateDir) != o.stateDir || filepath.Clean(exe) != exe || exe == "/" {
		return "", fmt.Errorf("print-unit requires absolute executable and dedicated state paths using only letters, digits, / . _ -")
	}
	if !safe(o.ifname) || strings.Contains(o.ifname, "/") || len(o.ifname) > 15 || o.ifname == "." || o.ifname == ".." {
		return "", fmt.Errorf("print-unit requires a literal interface name")
	}
	if o.authKey != "" || o.server != "" || o.network != "" || o.name != "" || o.advExit || o.advRoutes != "" || o.useExit != "" || o.sessHost || o.sessAuto || o.sessAllow != "" || o.sessRec != "" || o.sessProof || o.fakeTun || o.selfTest != "" || o.verbose || (o.proofDir != "" && o.proofDir != "/tmp/mnet-session-proof") {
		return "", fmt.Errorf("print-unit uses saved enrollment only; remove enrollment, routing, session and validation overrides (never put secrets in a unit)")
	}
	return fmt.Sprintf(`# Generated by mnetd -service print-unit. Review before installing.
# Enroll first with this same private state directory. Contains no auth key.
# Service running is not VPN readiness; use authenticated mnet wait/status.
[Unit]
Description=Mnet node daemon
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
UMask=0077
ExecStart=%s -state %s -ifname %s -up
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
`, exe, o.stateDir, o.ifname), nil
}
